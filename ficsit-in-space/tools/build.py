#!/usr/bin/env python3
"""Preflight the sheets, then generate the Space Engineers mod data from them.

    python3 tools/build.py            # preflight + generate
    python3 tools/build.py --check    # preflight only

Sheets are the source of truth. Every row becomes one generated struct entry
(C#) and, for items/recipes, one SBC definition.
"""
import json
import os
import sys
from xml.sax.saxutils import escape

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHEETS = os.path.join(ROOT, "sheets")
MOD = os.path.join(ROOT, "mod", "FicsitInSpace")

# Vanilla SE components whose model/icon a new item may borrow. The paths are
# only SBC placeholders: at load the script copies Model/Icons from the loaded
# vanilla definition, so the game's own values always win.
LOOKS_LIKE = {
    "SteelPlate": ("Models\\Components\\steel_plate_component.mwm", "Textures\\GUI\\Icons\\component\\steel_plate_component.dds"),
    "InteriorPlate": ("Models\\Components\\interior_plate_component.mwm", "Textures\\GUI\\Icons\\component\\interior_plate_component.dds"),
    "SmallTube": ("Models\\Components\\small_tube_component.mwm", "Textures\\GUI\\Icons\\component\\small_tube_component.dds"),
    "Construction": ("Models\\Components\\construction_components_component.mwm", "Textures\\GUI\\Icons\\component\\construction_components_component.dds"),
    "Motor": ("Models\\Components\\motor_component.mwm", "Textures\\GUI\\Icons\\component\\motor_icon.dds"),
    "MetalGrid": ("Models\\Components\\metal_grid_component.mwm", "Textures\\GUI\\Icons\\component\\metal_grid_component.dds"),
}
SE_TYPES = {"Ore", "Ingot", "Component"}


def load(name):
    with open(os.path.join(SHEETS, name + ".json"), encoding="utf-8") as f:
        sheet = json.load(f)
    return sheet["columns"], sheet["rows"]


def preflight():
    problems = []
    sheets = {n: load(n) for n in ("items", "recipes", "phases", "kit", "hooks")}

    # 1. every row x column crossing filled
    for name, (cols, rows) in sheets.items():
        for i, row in enumerate(rows):
            for c in cols:
                v = row.get(c)
                if v is None or v == "":
                    problems.append(f"{name}[{i}].{c}: empty")
            for c in row:
                if c not in cols:
                    problems.append(f"{name}[{i}].{c}: column not declared")

    items = {r["key"]: r for r in sheets["items"][1]}
    # 2. cross references
    for r in items.values():
        t, _, s = r["seId"].partition("/")
        if t not in SE_TYPES or not s:
            problems.append(f"items.{r['key']}.seId: bad id {r['seId']}")
        if r["kind"] == "new":
            if r["looksLike"] not in LOOKS_LIKE:
                problems.append(f"items.{r['key']}.looksLike: unknown {r['looksLike']}")
            if t != "Component" or not s.startswith("FIS_"):
                problems.append(f"items.{r['key']}.seId: new items must be Component/FIS_*")
            for c in ("mass", "volume", "maxIntegrity"):
                if not isinstance(r[c], (int, float)) or r[c] <= 0:
                    problems.append(f"items.{r['key']}.{c}: must be > 0")
        elif r["kind"] != "vanilla":
            problems.append(f"items.{r['key']}.kind: {r['kind']}")
    if len({r["satClass"] for r in items.values()}) != len(items):
        problems.append("items: duplicate satClass")
    for r in sheets["recipes"][1]:
        if r["output"] not in items:
            problems.append(f"recipes.{r['key']}.output: no item {r['output']}")
        elif items[r["output"]]["kind"] != "new":
            problems.append(f"recipes.{r['key']}.output: must be a new item")
    for sheet in ("phases", "kit"):
        for i, r in enumerate(sheets[sheet][1]):
            if r["item"] not in items:
                problems.append(f"{sheet}[{i}].item: no item {r['item']}")
            if not isinstance(r["amount"], int) or r["amount"] <= 0:
                problems.append(f"{sheet}[{i}].amount: must be int > 0")
    # every new item must be craftable (SE may crash on components without a blueprint)
    made = {r["output"] for r in sheets["recipes"][1]}
    for r in items.values():
        if r["kind"] == "new" and r["key"] not in made:
            problems.append(f"items.{r['key']}: new component has no recipe")

    # 3. unverified cells (reported, not fatal: they need the running game)
    unverified = [f"hooks.{r['key']}" for r in sheets["hooks"][1] if r["verified"] == "needs-game"]
    return sheets, problems, unverified


def cs(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def generate(sheets):
    items = sheets["items"][1]
    by_key = {r["key"]: r for r in items}
    os.makedirs(os.path.join(MOD, "Data", "Scripts", "FicsitInSpace"), exist_ok=True)

    head = ('<?xml version="1.0"?>\n<!-- GENERATED by tools/build.py from sheets/. Do not edit. -->\n'
            '<Definitions xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" '
            'xmlns:xsd="http://www.w3.org/2001/XMLSchema">\n')

    out = [head, "  <Components>\n"]
    for r in items:
        if r["kind"] != "new":
            continue
        model, icon = LOOKS_LIKE[r["looksLike"]]
        sub = r["seId"].split("/")[1]
        # Display name is a neutral placeholder; the real name comes from the
        # player's Satisfactory Docs file at load.
        out.append(f"""    <Component>
      <Id><TypeId>Component</TypeId><SubtypeId>{sub}</SubtypeId></Id>
      <DisplayName>FICSIT {escape(r['key'])}</DisplayName>
      <Description>Needs Satisfactory installed (names and recipes are read from it).</Description>
      <Icon>{escape(icon)}</Icon>
      <Size><X>0.2</X><Y>0.2</Y><Z>0.2</Z></Size>
      <Mass>{r['mass']}</Mass>
      <Volume>{r['volume']}</Volume>
      <Model>{escape(model)}</Model>
      <PhysicalMaterial>Metal</PhysicalMaterial>
      <MaxIntegrity>{r['maxIntegrity']}</MaxIntegrity>
      <DropProbability>0.9</DropProbability>
      <Health>10</Health>
    </Component>
""")
    out.append("  </Components>\n</Definitions>\n")
    write(os.path.join(MOD, "Data", "FIS_Components.sbc"), "".join(out))

    out = [head, "  <Blueprints>\n"]
    entries = []
    for r in sheets["recipes"][1]:
        o = by_key[r["output"]]
        t, sub = o["seId"].split("/")
        model, icon = LOOKS_LIKE[o["looksLike"]]
        out.append(f"""    <Blueprint>
      <Id><TypeId>BlueprintDefinition</TypeId><SubtypeId>{r['seBlueprint']}</SubtypeId></Id>
      <DisplayName>FICSIT {escape(r['key'])}</DisplayName>
      <Icon>{escape(icon)}</Icon>
      <Prerequisites><Item Amount="1" TypeId="Ingot" SubtypeId="Iron" /></Prerequisites>
      <Result Amount="1" TypeId="{t}" SubtypeId="{sub}" />
      <BaseProductionTimeInSeconds>1</BaseProductionTimeInSeconds>
    </Blueprint>
""")
        entries.append(f'    <Entry Class="{r["seBlueprintClass"]}" BlueprintSubtypeId="{r["seBlueprint"]}" />\n')
    out.append("  </Blueprints>\n  <BlueprintClassEntries>\n")
    out += entries
    out.append("  </BlueprintClassEntries>\n</Definitions>\n")
    write(os.path.join(MOD, "Data", "FIS_Blueprints.sbc"), "".join(out))

    c = ["// GENERATED by tools/build.py from sheets/. Do not edit.\n",
         "namespace FicsitInSpace\n{\n",
         "    public struct ItemRow { public string Key, SatClass, Kind, SeType, SeSubtype, LooksLike;\n",
         "        public ItemRow(string k, string s, string kind, string t, string sub, string l) { Key = k; SatClass = s; Kind = kind; SeType = t; SeSubtype = sub; LooksLike = l; } }\n",
         "    public struct RecipeRow { public string Key, SatRecipe, SeBlueprint, Output;\n",
         "        public RecipeRow(string k, string r, string b, string o) { Key = k; SatRecipe = r; SeBlueprint = b; Output = o; } }\n",
         "    public struct AmountRow { public int Phase; public string Item; public int Amount;\n",
         "        public AmountRow(int p, string i, int a) { Phase = p; Item = i; Amount = a; } }\n\n",
         "    public static class Sheets\n    {\n",
         "        public static readonly ItemRow[] Items = {\n"]
    for r in items:
        t, sub = r["seId"].split("/")
        c.append(f"            new ItemRow({cs(r['key'])}, {cs(r['satClass'])}, {cs(r['kind'])}, {cs(t)}, {cs(sub)}, {cs(r['looksLike'])}),\n")
    c.append("        };\n        public static readonly RecipeRow[] Recipes = {\n")
    for r in sheets["recipes"][1]:
        c.append(f"            new RecipeRow({cs(r['key'])}, {cs(r['satRecipe'])}, {cs(r['seBlueprint'])}, {cs(r['output'])}),\n")
    c.append("        };\n        public static readonly AmountRow[] Phases = {\n")
    for r in sheets["phases"][1]:
        c.append(f"            new AmountRow({r['phase']}, {cs(r['item'])}, {r['amount']}),\n")
    c.append("        };\n        public static readonly AmountRow[] Kit = {\n")
    for r in sheets["kit"][1]:
        c.append(f"            new AmountRow(0, {cs(r['item'])}, {r['amount']}),\n")
    c.append("        };\n    }\n}\n")
    write(os.path.join(MOD, "Data", "Scripts", "FicsitInSpace", "SheetData.cs"), "".join(c))


def write(path, text):
    with open(path, "w", encoding="utf-8", newline="\r\n") as f:
        f.write(text)
    print("wrote", os.path.relpath(path, ROOT))


if __name__ == "__main__":
    sheets, problems, unverified = preflight()
    print(f"preflight: {len(problems)} problem(s)")
    for p in problems:
        print("  FAIL", p)
    for u in unverified:
        print("  UNVERIFIED (needs running game)", u)
    if problems:
        sys.exit(1)
    if "--check" not in sys.argv:
        generate(sheets)
